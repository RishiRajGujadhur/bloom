export function PixelArt({
  category,
  journalId,
}: {
  category: JournalCategory
  journalId?: string
}) {
  const pixels =
    (journalId && journalPixelPatterns[journalId]) || patterns[category]
  return (
    <svg
      className="daybook-pixel-art"
      viewBox="0 0 96 96"
      aria-hidden="true"
      shapeRendering="crispEdges"
      data-journal-icon={journalId}
    >
      {pixels.flatMap((row, y) =>
        Array.from(row).map((pixel, x) =>
          pixel === '1' ? (
            <rect
              key={`${x}:${y}`}
              x={8 + x * 10}
              y={8 + y * 10}
              width="9"
              height="9"
              style={
                {
                  '--pixel-delay': `${((x * 7 + y * 11) % 9) * 35}ms`,
                  '--pixel-shift': `${((x % 3) - 1) * 7}px`,
                } as CSSProperties
              }
            />
          ) : null,
        ),
      )}
    </svg>
  )
}
